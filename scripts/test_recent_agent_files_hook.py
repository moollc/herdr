        generator = self.outside / "generate.py"
        generator.write_text(
            "from pathlib import Path\n"
            "import json\n"
            f"target = Path({str(output)!r})\n"
            "target.write_text('{\\\"generated\\\":true}')\n"
            "print(json.dumps({'herdr_write_manifest': {'version': 1, 'success': True, 'files': [str(target)]}}))\n"
        )
        command = "python3 " + shlex.quote(str(generator))
        pre = {"tool_name": "Bash", "tool_use_id": "generator-write-event", "cwd": str(self.cwd),
               "tool_input": {"command": command}}
