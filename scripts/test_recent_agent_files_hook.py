    def test_managed_state_fallback_rejects_unmanaged_and_unknown_or_symlink_sockets(self):
        valid_socket = self.managed_socket()
        common = {"HERDR_ENV": "1", "HERDR_PANE_ID": "fixture-pane",
                  "HERDR_SOCKET_PATH": str(valid_socket), "HOME": str(self.base),
                  "XDG_CONFIG_HOME": str(self.base / "xdg-config")}
        self.assertEqual(hook._state_dir_from_environment(common),
                         str(self.base / ".local/state/herdr"))
        self.assertIsNone(hook._state_dir_from_environment({**common, "HERDR_ENV": "0"}))
        self.assertIsNone(hook._state_dir_from_environment({k: v for k, v in common.items()
                                                            if k != "HERDR_PANE_ID"}))
        unknown_socket = self.base / "custom" / "herdr.sock"
        unknown_socket.parent.mkdir()
        unknown_listener = socket.socket(socket.AF_UNIX)
        unknown_listener.bind(str(unknown_socket))
        self.addCleanup(unknown_listener.close)
        self.assertIsNone(hook._state_dir_from_environment({**common,
                                                            "HERDR_SOCKET_PATH": str(unknown_socket)}))
        link = self.base / "socket-link"
        link.symlink_to(valid_socket)
        self.assertIsNone(hook._state_dir_from_environment({**common, "HERDR_SOCKET_PATH": str(link)}))
        debug_socket = self.managed_socket("herdr-dev", named=False)
        debug_env = {**common, "HERDR_SOCKET_PATH": str(debug_socket), "HOME": str(self.base)}
        self.assertEqual(hook._state_dir_from_environment(debug_env),
                         str(self.base / ".local/state/herdr-dev"))

    def codex(self, tool, tool_id, command_or_args, *, before=True, response="tool returned text"):
        payload = {"tool_name": tool, "tool_use_id": tool_id, "cwd": str(self.cwd),
                   "tool_input": command_or_args}
        if before:
            self.run_hook("codex", "PreToolUse", payload)
        payload["tool_response"] = response
        return payload, self.run_hook("codex", "PostToolUse", payload)

    def test_codex_bash_creation_outside_cwd_uses_real_pre_post_id_and_string_response(self):
        path = self.outside / "shell output.txt"
        command = "printf harmless > '" + str(path) + "'"
        pre = {"tool_name": "Bash", "tool_use_id": "bash-event-opaque", "cwd": str(self.cwd),
               "tool_input": {"command": command}}
        self.run_hook("codex", "PreToolUse", pre)
        pending = (self.state / hook.PENDING_NAME).read_text()
        self.assertNotIn(command, pending)
        self.assertNotIn("harmless", pending)
        self.assertNotIn("bash-event-opaque", pending)
        path.write_text("harmless fixture content")
        self.run_hook("codex", "PostToolUse", {**pre, "tool_response": "Process exited with code 0"})
        self.assertEqual(self.records()[0]["path"], str(path.resolve()))
        journal = (self.state / hook.JOURNAL_NAME).read_text()
        self.assertNotIn("harmless fixture content", journal)
        self.assertNotIn(command, journal)

