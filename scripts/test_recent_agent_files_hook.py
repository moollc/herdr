class RecentAgentFilesHookTests(unittest.TestCase):
    def setUp(self):
        self.base = Path(tempfile.mkdtemp(prefix="hraf-", dir="/tmp"))
        self.cwd = self.base / "workspace"
        self.cwd.mkdir()
        self.state = self.base / "herdr-state"
        self.outside = self.base / "outside cwd"
        self.outside.mkdir()

    def records(self):
        path = self.state / hook.JOURNAL_NAME
        return [json.loads(line) for line in path.read_text().splitlines()] if path.exists() else []

    def run_hook(self, provider, event, payload, state_dir=None):
        state_dir = state_dir or self.state
        env = dict(os.environ, HERDR_ENV="1", HERDR_PANE_ID="fixture-pane", HERDR_STATE_DIR=str(state_dir))
        return subprocess.run(
            [sys.executable, str(ASSET), provider, event],
            input=json.dumps(payload), text=True, capture_output=True, env=env, check=True,
        )

    def managed_socket(self, app_dir="herdr", *, named=True):
        config_root = self.base / "xdg-config" / app_dir
        socket_path = config_root / "sessions" / "fixture" / "herdr.sock" if named else config_root / "herdr.sock"
        socket_path.parent.mkdir(parents=True, exist_ok=True)
        listener = socket.socket(socket.AF_UNIX)
        listener.bind(str(socket_path))
        self.addCleanup(listener.close)
        return socket_path

    def run_hook_without_state_env(self, provider, event, payload, env):
        return subprocess.run(
            [sys.executable, str(ASSET), provider, event], input=json.dumps(payload),
            text=True, capture_output=True, env=env, check=True,
        )

    def test_missing_state_env_actual_bash_manifest_resolves_managed_xdg_state(self):
        socket_path = self.managed_socket()
        state_root = self.base / "xdg-state" / "herdr"
        output = self.outside / "actual-native-shape.txt"
        common = {
            "tool_name": "Bash", "tool_use_id": "missing-state-real-pre-post",
            "cwd": str(self.cwd), "tool_input": {"command": "python3 generator.py"},
        }
        env = dict(os.environ, HERDR_ENV="1", HERDR_PANE_ID="fixture-pane",
                   HERDR_SOCKET_PATH=str(socket_path), XDG_CONFIG_HOME=str(self.base / "xdg-config"),
                   HOME=str(self.base / "home"),
                   XDG_STATE_HOME=str(self.base / "xdg-state"),
                   HERDR_CONFIG_PATH=str(self.base / "custom-herdr.toml"))
        env.pop("HERDR_STATE_DIR", None)
        self.run_hook_without_state_env("codex", "PreToolUse", common, env)
        output.write_text("generated by supported manifest event")
        response = json.dumps({"herdr_write_manifest": {"version": 1, "success": True,
                                                          "files": [str(output)]}})
        self.run_hook_without_state_env("codex", "PostToolUse",
                                        {**common, "tool_response": response}, env)
        rows = [json.loads(line) for line in (state_root / hook.JOURNAL_NAME).read_text().splitlines()]
        self.assertEqual([row.get("path") for row in rows if row.get("path")], [str(output.resolve())])
        self.assertFalse((Path(env["HOME"]) / ".local/state/herdr" / hook.JOURNAL_NAME).exists())

    def test_explicit_nondefault_state_env_precedes_verified_fallback(self):
        socket_path = self.managed_socket()
        explicit_state = self.base / "explicit-state-location"
        fallback_state = self.base / "xdg-state" / "herdr"
        path = self.outside / "explicit-state-write.txt"
